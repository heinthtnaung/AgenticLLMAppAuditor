"""Manifests and lock files real enough for Syft to read, for the live measurement.

Each lock pins one package, so a case either yields that package or yields
nothing, and the test can say which. They are close to what each tool writes,
because a sample Syft cannot parse yields nothing and reads exactly like a lock
Syft does not read: a `yarn.lock` with no header, unquoted keys and a made-up
checksum was measured yielding nothing, and this one yields lodash.

Named `lock_samples` and not `samples`: pytest puts each test directory on the
path and imports by basename, and `tests/deps/samples.py` is taken.
"""

import json

INTEGRITY = (
    "sha512-PlhdFcillOINfeV7Ni6oF1TAEayyZBoZ8bcshTwg3zc5SthqpZt6Pnfqhzfe"
    "/H+OXkpUyU1+KaRt1IvyEdhm+w=="
)
LODASH_TARBALL = "https://registry.npmjs.org/lodash/-/lodash-4.17.20.tgz"
NEEDS_LODASH = {"lodash": "4.17.20"}
LOCKED_LODASH = {"version": "4.17.20", "resolved": LODASH_TARBALL, "integrity": INTEGRITY}

PACKAGE_JSON = json.dumps({"name": "demo", "version": "1.0.0", "dependencies": NEEDS_LODASH})
PACKAGE_LOCK = json.dumps({
    "name": "demo", "version": "1.0.0", "lockfileVersion": 3, "requires": True,
    "packages": {
        "": {"name": "demo", "version": "1.0.0", "dependencies": NEEDS_LODASH},
        "node_modules/lodash": LOCKED_LODASH,
    },
})
YARN_LOCK = "\n".join([
    "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.",
    "# yarn lockfile v1", "", "",
    '"lodash@4.17.20":',
    '  version "4.17.20"',
    f'  resolved "{LODASH_TARBALL}#b44a9b6297bcb698f1c51a3545a2b3b368d59c52"',
    f"  integrity {INTEGRITY}", "",
])
PNPM_LOCK = "\n".join([
    "lockfileVersion: '6.0'",
    "dependencies:", "  lodash:", "    specifier: 4.17.20", "    version: 4.17.20",
    "packages:", "  /lodash@4.17.20:", f"    resolution: {{integrity: {INTEGRITY}}}",
    "    dev: false", "",
])
INSTALLED_LODASH = json.dumps({"name": "lodash", "version": "4.17.20"})

COMPOSER_JSON = json.dumps({"name": "demo/demo", "require": {"monolog/monolog": "2.0.0"}})
COMPOSER_LOCK = json.dumps({
    "packages": [{"name": "monolog/monolog", "version": "2.0.0", "type": "library"}],
    "packages-dev": [],
})

GEMFILE = 'source "https://rubygems.org"\ngem "rails", "6.0.0"\n'
GEMFILE_LOCK = "\n".join([
    "GEM", "  remote: https://rubygems.org/", "  specs:", "    rails (6.0.0)", "",
    "PLATFORMS", "  ruby", "", "DEPENDENCIES", "  rails (= 6.0.0)", "",
    "BUNDLED WITH", "   2.1.4", "",
])

# Every manifest and lock the table names, so a lock added to the table with no
# sample here fails the live test by name rather than passing it by omission.
MANIFESTS = {"package.json": PACKAGE_JSON, "composer.json": COMPOSER_JSON, "Gemfile": GEMFILE}
LOCKS = {
    "package-lock.json": PACKAGE_LOCK,
    "yarn.lock": YARN_LOCK,
    "pnpm-lock.yaml": PNPM_LOCK,
    "composer.lock": COMPOSER_LOCK,
    "Gemfile.lock": GEMFILE_LOCK,
}
LOCKED_PACKAGE = {"package.json": "lodash", "composer.json": "monolog/monolog", "Gemfile": "rails"}

# Measured yielding nothing alone, and left out of the table on purpose.
LEFT_OUT = {
    "Cargo.toml": '[package]\nname = "demo"\nversion = "0.1.0"\n\n[dependencies]\nserde = "1.0"\n',
    "pyproject.toml": '[project]\nname = "demo"\nversion = "0.1.0"\ndependencies = ["requests"]\n',
}

# An npm workspace: the member declares lodash, and only the root holds a lock.
MEMBER = {"name": "a", "version": "1.0.0", "dependencies": NEEDS_LODASH}
WORKSPACE = {
    "package.json": json.dumps({"name": "root", "version": "1.0.0", "workspaces": ["packages/a"]}),
    "packages/a/package.json": json.dumps(MEMBER),
    "package-lock.json": json.dumps({
        "name": "root", "version": "1.0.0", "lockfileVersion": 3, "requires": True,
        "packages": {
            "": {"name": "root", "version": "1.0.0", "workspaces": ["packages/a"]},
            "node_modules/a": {"resolved": "packages/a", "link": True},
            "node_modules/lodash": LOCKED_LODASH,
            "packages/a": MEMBER,
        },
    }),
}
